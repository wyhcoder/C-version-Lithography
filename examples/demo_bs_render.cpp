static void save_mat_txt(const Eigen::MatrixXd& M, const std::string& fname){
    std::ofstream f(fname);
    for (int r = 0; r < M.rows(); ++r){
        for (int c = 0; c < M.cols(); ++c){
            f << M(r,c);
            if (c < M.cols() - 1) f << " ";
        }
        f << "\n";
    }
    std::cout << "  已保存: " << fname << "\n";
}

// 对【y，x】对进行处理使其成为 [N x 2] 的 Contour
static Eigen::MatrixXd make_contour(std::initializer_list<std::pair<double,double>> pts){
    Eigen::MatrixXd m(static_cast<int>(pts.size()),2);
    int i = 0;
    for(auto [y,x] : pts){
        m(i,0)=y;
        m(i,1)=x;
        ++i;
    }
    return m;
}

